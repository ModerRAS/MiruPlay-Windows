// i18n build: node tools/i18n/build.js [--check]
// Reads tools/i18n/strings.json, verifies parity, and regenerates:
//   src/MiruPlay.Windows/Web/i18n.js               (dict + runtime)
//   src/MiruPlay.Windows/Resources/Strings.resx     (zh-CN master)
//   src/MiruPlay.Windows/Resources/Strings.{zh-TW,zh-HK,en-US,en-GB}.resx
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '../..');
const tablePath = path.join(__dirname, 'strings.json');
const locales = ['zh-CN', 'zh-TW', 'zh-HK', 'en-US', 'en-GB'];
const checkOnly = process.argv.includes('--check');

function fail(message) { console.error('i18n: ' + message); process.exit(1); }

const raw = JSON.parse(fs.readFileSync(tablePath, 'utf8'));
const keys = Object.keys(raw).filter(k => !k.startsWith('_'));
const ph = s => [...(s.match(/\{(\d+)\}/g) || [])].sort().join(',');

const errors = [];
for (const key of keys) {
  const entry = raw[key];
  for (const loc of locales) {
    if (typeof entry[loc] !== 'string' || entry[loc].length === 0)
      errors.push(`${key}: missing/empty ${loc}`);
  }
  const base = ph(entry['zh-CN'] || '');
  for (const loc of locales) {
    if (ph(entry[loc] || '') !== base) errors.push(`${key}: placeholder mismatch in ${loc}`);
  }
}
// referenced-key coverage for app.js
const appJs = fs.readFileSync(path.join(root, 'src/MiruPlay.Windows/Web/app.js'), 'utf8');
const used = new Set([...appJs.matchAll(/\bt\(\s*['\"]([^'\"]+)['\"]/g)].map(m => m[1]));
for (const key of used) {
  if (!keys.includes(key)) errors.push(`app.js uses unknown key ${key}`);
}
for (const line of require('child_process').execSync(
  'C:/Users/ModerRAS/.pi/agent/bin/rg.exe -o -N --no-filename "services:Loc" src/MiruPlay.Windows --glob "*.xaml"',
  { cwd: root, encoding: 'utf8' }).split('\n')) {
  const m = /services:Loc (?:Key=)?([a-z0-9._-]+)/.exec(line);
  if (m && !keys.includes(m[1])) errors.push(`XAML uses unknown key ${m[1]}`);
}
for (const line of require('child_process').execSync(
  'C:/Users/ModerRAS/.pi/agent/bin/rg.exe -o -N --no-filename "AppStrings.Get" src/MiruPlay.Windows --glob "*.cs"',
  { cwd: root, encoding: 'utf8' }).split('\n')) {
  const m = /AppStrings\.Get\("([^"]+)"/.exec(line);
  if (m && !keys.includes(m[1])) errors.push(`C# uses unknown key ${m[1]}`);
}
if (errors.length) fail(errors.slice(0, 30).join('\n') + (errors.length > 30 ? `\n... +${errors.length - 30} more` : ''));

if (checkOnly) { console.log(`i18n OK: ${keys.length} keys x ${locales.length} locales, ${used.size} used by app.js`); return; }

const escXml = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const resxHead = `<?xml version="1.0" encoding="utf-8"?>\n<root>\n  <resheader name="resmimetype"><value>text/microsoft-resx</value></resheader>\n  <resheader name="version"><value>2.0</value></resheader>\n  <resheader name="reader"><value>System.Resources.ResXResourceReader, System.Windows.Forms</value></resheader>\n  <resheader name="writer"><value>System.Resources.ResXResourceWriter, System.Windows.Forms</value></resheader>\n`;
for (const loc of locales) {
  const name = loc === 'zh-CN' ? 'Strings.resx' : `Strings.${loc}.resx`;
  let xml = resxHead;
  for (const key of keys) xml += `  <data name="${escXml(key)}" xml:space="preserve"><value>${escXml(raw[key][loc])}</value></data>\n`;
  xml += '</root>\n';
  fs.mkdirSync(path.join(root, 'src/MiruPlay.Windows/Resources'), { recursive: true });
  fs.writeFileSync(path.join(root, 'src/MiruPlay.Windows/Resources', name), xml);
}

const runtime = `// GENERATED by tools/i18n/build.js — do not hand-edit the dict.
const I18N = ${JSON.stringify(Object.fromEntries(locales.map(l => [l, Object.fromEntries(keys.map(k => [k, raw[k][l]]))])), null, 1)};
let currentLocale = 'zh-CN';
export function setLocale(locale) { currentLocale = I18N[locale] ? locale : 'zh-CN'; document.documentElement.lang = currentLocale; }
export function getLocale() { return currentLocale; }
export function supportedWebLocales() { return ${JSON.stringify(locales)}; }
export function t(key, ...args) {
  const table = I18N[currentLocale] || {};
  let s = table[key] ?? (I18N['zh-CN'] || {})[key] ?? key;
  args.forEach((a, i) => { s = s.split('{' + i + '}').join(String(a ?? '')); });
  return s;
}
`;
fs.writeFileSync(path.join(root, 'src/MiruPlay.Windows/Web/i18n.js'), runtime);
console.log(`i18n built: ${keys.length} keys`);
